/** Localize system-owned UI text; the optional service makes formatters directly testable. */
export function uiText(english, data = {}, i18n = globalThis.game?.i18n) {
  const key = Object.hasOwn(keys, english) ? keys[english] : undefined;
  const localized = key && i18n?.localize ? i18n.localize(key) : english;
  const template = localized === key ? english : localized;
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(data, name) ? String(data[name]) : match);
}

// Match only complete system messages. Captured names/keys are opaque user content.
const patterns = Object.keys(keys).filter(text => /\{\w+\}/.test(text)).map(text => {
  const names = [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]);
  const parts = text.split(/\{\w+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return { text, names, pattern: new RegExp(`^${parts.join("(.*?)")}$`, "s") };
});

/** Recognition depends on the catalog, never on whether translation changes the wording. */
export function isSystemMessage(message) {
  if (!message) return false;
  if (Object.hasOwn(keys, message)) return true;
  if (message.includes("\n")) return message.split("\n").some(isSystemMessage);
  if (patterns.some(({ pattern }) => pattern.test(message))) return true;
  const index = message.lastIndexOf(": Stored legacy Success Threshold ");
  return index >= 0 && isSystemMessage(message.slice(index + 2));
}

/** Adapt messages from pure services at the presentation boundary, without changing thrown errors. */
export function systemMessage(message, i18n = globalThis.game?.i18n) {
  if (!message) return message;
  if (Object.hasOwn(keys, message)) return uiText(message, {}, i18n);
  if (message.includes("\n")) return message.split("\n").map(line => systemMessage(line, i18n)).join("\n");
  for (const { text, names, pattern } of patterns) {
    const match = pattern.exec(message);
    if (!match) continue;
    const data = Object.fromEntries(names.map((name, index) => [name, match[index + 1]]));
    if (data.stance) data.stance = uiText(data.stance[0].toUpperCase() + data.stance.slice(1), {}, i18n);
    if (data.conditions) data.conditions = data.conditions.split(" and ").map(value => uiText(value, {}, i18n)).join(` ${uiText("and", {}, i18n)} `);
    if (data.label) data.label = uiText(data.label, {}, i18n);
    return uiText(text, data, i18n);
  }
  // Legacy threshold review may be prefixed with an opaque Action name.
  const marker = ": Stored legacy Success Threshold ";
  const index = message.lastIndexOf(marker);
  if (index >= 0) return message.slice(0, index + 2) + systemMessage(message.slice(index + 2), i18n);
  return message;
}
